import assert from 'node:assert/strict';
import vm from 'node:vm';
import { buildBrowserObserver } from '../tools/build-browser-observer.mjs';
import { describeComputeReceipt } from '../engine/compute-presentation.js';
import { distanceKm } from '../engine/v9-geodesy.js';
const sandbox = {};
vm.runInNewContext(buildBrowserObserver(), sandbox);
const api = sandbox.VentusGridCompute;
const observer = api.createComputeObserver();
const entity = {kind:'repd',id:'12588'}, location={lon:-1.3489728,lat:51.8132088};
const id=observer.request({entity,location});
assert.equal(api.describeComputeReceipt(observer.snapshot()).status,'requested');
const node={node_id:'test-node',lon:-1.35,lat:51.8};
let invoked=0;
const completed=await observer.run(id,()=>{invoked++;return {entity,origin:location,measurements:[{...node,km:distanceKm(location.lon,location.lat,node.lon,node.lat)}]};});
assert.equal(invoked,1);
assert.equal(completed.status,'completed');
assert.equal(api.describeComputeReceipt(completed).unit,'km');
assert.equal(JSON.stringify(api.describeComputeReceipt(completed)),JSON.stringify(describeComputeReceipt(completed)));
assert.match(api.describeComputeReceipt(completed).scope,/not an electrical connection/);
assert.equal(describeComputeReceipt({status:'failed',reason:'dataset unavailable'}).distance_km,null);
assert.equal(describeComputeReceipt(null).status,'not_requested');
assert.equal(buildBrowserObserver(),buildBrowserObserver());
console.log('browser observer PASS — 9 checks');
